#!/usr/bin/env bash
# Start a video project from the skill's template: composition, helper scripts, vendored GSAP and a font.
#   bash <skill>/scripts/new-project.sh <slug>          → $PROMO_VIDEO_HOME/<slug> (default ~/promo-videos/<slug>)
#   bash <skill>/scripts/new-project.sh <path/to/dir>   → that directory
# Video projects live outside every git repository: neither the media nor the composition code is committed.
# Then run the template once (see the skill's "Build loop") before replacing its content.
set -euo pipefail
ARG=${1:?usage: new-project.sh <slug> | <path>}
SKILL=$(cd "$(dirname "$0")/.." && pwd)
VIDEO_HOME=${PROMO_VIDEO_HOME:-$HOME/promo-videos}
GSAP_VERSION=3.14.2
INTER_VERSION=5.2.8

case "$ARG" in
  */*) DEST=$ARG ;;
  *) DEST=$VIDEO_HOME/$ARG ;;
esac
SLUG=$(basename "$DEST")
if ! [[ $SLUG =~ ^[a-z0-9]+(-[a-z0-9]+)*$ ]]; then
  echo "project name '$SLUG' must be a lowercase slug (a-z, 0-9, single hyphens): it names the renders" >&2; exit 1
fi
if [ -e "$DEST/index.html" ]; then echo "$DEST/index.html exists; not overwriting" >&2; exit 1; fi

# refuse to start inside a git work tree: renders, captures and voice takes must never reach a repository
PARENT=$(dirname "$DEST")
while [ ! -d "$PARENT" ]; do PARENT=$(dirname "$PARENT"); done
if git -C "$PARENT" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  echo "$PARENT is inside the git repository $(git -C "$PARENT" rev-parse --show-toplevel)." >&2
  echo "Video projects live outside repositories: pass a slug (→ $VIDEO_HOME/<slug>) or set PROMO_VIDEO_HOME." >&2
  exit 1
fi

mkdir -p "$DEST/scripts" "$DEST/assets/js" "$DEST/assets/vendor" "$DEST/assets/fonts" "$DEST/audio/vo" \
  "$DEST/renders" "$DEST/review"
cp "$SKILL/assets/index.html" "$DEST/index.html"
cp "$SKILL/assets/scene.js" "$DEST/assets/js/scene.js"
cp "$SKILL/assets/script.json" "$DEST/audio/vo/script.json"
for f in "$SKILL"/scripts/*; do
  [ "$(basename "$f")" = "new-project.sh" ] || cp "$f" "$DEST/scripts/"
done
# stubs until build_vo.py and build_captions.py overwrite them
printf '%s\n' '// generated by scripts/build_vo.py; empty until the project has a voiceover' 'window.VO = [];' 'window.VO_TOTAL = null;' > "$DEST/assets/timing.js"
printf '%s\n' '// generated by scripts/build_captions.py; empty until the project has a voiceover' 'window.CAPTIONS = [];' > "$DEST/assets/captions.js"

# the project record and the facts sheet start as skeletons (references/delivery.md, references/story.md)
[ -e "$DEST/README.md" ] || cat > "$DEST/README.md" <<EOF
# $SLUG

Status: not rendered yet.

## Output
## Decisions
## Simplified or made up on screen
## Sources and licenses
## Loudness
## Rebuild
## Publications
EOF
[ -e "$DEST/facts.md" ] || cat > "$DEST/facts.md" <<'EOF'
# Facts

| Claim | Source (URL or file, date read) |
|---|---|

## Made up on screen

## Don't claim
EOF

curl -fsSL -o "$DEST/assets/vendor/gsap.min.js" "https://cdn.jsdelivr.net/npm/gsap@$GSAP_VERSION/dist/gsap.min.js"
curl -fsSL -o "$DEST/assets/fonts/inter-latin-wght-normal.woff2" "https://cdn.jsdelivr.net/npm/@fontsource-variable/inter@$INTER_VERSION/files/inter-latin-wght-normal.woff2"
curl -fsSL -o "$DEST/assets/fonts/LICENSE-Inter.txt" "https://cdn.jsdelivr.net/npm/@fontsource-variable/inter@$INTER_VERSION/LICENSE"

echo "project ready in $DEST (GSAP $GSAP_VERSION, Inter $INTER_VERSION)"
